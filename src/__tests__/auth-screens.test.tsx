import { fireEvent, render, screen, waitFor, within } from '@testing-library/react-native';
import { Platform, StyleSheet } from 'react-native';

// Native ESM Jest mode does not hoist factories the way Babel's CJS jest-hoist plugin would (see
// authService.test.ts's module doc) — every mock factory below is a literal object or inline
// `jest.fn()`, never a reference to an outer-scope `const`. These three screens are rendered in
// isolation here (no real navigator), so `expo-router`'s `router` is mocked — route-guard/real
// navigation behavior is covered separately in auth-guards.test.tsx via `expo-router/testing-library`.
jest.mock('../auth/authService', () => ({
  signUpWithEmail: jest.fn(),
  signInWithEmail: jest.fn(),
  requestPasswordReset: jest.fn(),
  confirmPasswordReset: jest.fn(),
  signInWithApple: jest.fn(),
  signInWithGoogle: jest.fn(),
  signOut: jest.fn(),
}));

jest.mock('expo-router', () => ({
  router: { push: jest.fn(), replace: jest.fn(), back: jest.fn(), canGoBack: jest.fn(() => true) },
}));

// SocialButton renders the real `AppleAuthenticationButton` for the Apple provider. Under
// jest-expo there's no native Apple Authentication UI, so this mock stands in for it as a plain
// pressable exposing the same `onPress` prop and an English accessible name — matching what the
// real native button renders on a device whose language list includes English (its label is
// generated by iOS itself from `buttonType`, not by this app, so the mock doesn't read `t(...)`).
jest.mock('expo-apple-authentication', () => ({
  AppleAuthenticationButton: (props: { onPress: () => void }) => {
    const { Pressable, Text } = jest.requireActual<typeof import('react-native')>('react-native');
    return (
      <Pressable accessibilityRole="button" accessibilityLabel="Continue with Apple" onPress={props.onPress}>
        <Text>Continue with Apple</Text>
      </Pressable>
    );
  },
  AppleAuthenticationButtonType: { CONTINUE: 1 },
  AppleAuthenticationButtonStyle: { BLACK: 2 },
}));

import { router } from 'expo-router';

import {
  confirmPasswordReset,
  requestPasswordReset,
  signInWithApple,
  signInWithEmail,
  signInWithGoogle,
  signUpWithEmail,
} from '../auth/authService';
import ForgotPasswordScreen from '../app/(auth)/forgot-password';
import SignInScreen from '../app/(auth)/sign-in';
import WelcomeScreen from '../app/(auth)/welcome';

const mockedSignUpWithEmail = jest.mocked(signUpWithEmail);
const mockedSignInWithEmail = jest.mocked(signInWithEmail);
const mockedRequestPasswordReset = jest.mocked(requestPasswordReset);
const mockedConfirmPasswordReset = jest.mocked(confirmPasswordReset);
const mockedSignInWithApple = jest.mocked(signInWithApple);
const mockedSignInWithGoogle = jest.mocked(signInWithGoogle);

beforeEach(() => {
  jest.clearAllMocks();
  jest.mocked(router.canGoBack).mockReturnValue(true);
});

describe('WelcomeScreen', () => {
  test('shows a two-line hero headline, the language toggle, Apple/Google, placeholder-only fields and footer links on iOS', async () => {
    Platform.OS = 'ios';
    await render(<WelcomeScreen />);

    expect(screen.getByText('DRESS\nWITHOUT DOUBT')).toBeTruthy();
    expect(screen.getByRole('tab', { name: 'Español' })).toBeTruthy();
    expect(screen.getByRole('tab', { name: 'English' })).toBeTruthy();
    expect(screen.getByRole('button', { name: 'Continue with Apple' })).toBeTruthy();
    expect(screen.getByRole('button', { name: 'Continue with Google' })).toBeTruthy();
    // Placeholder-only: the accessible label is still "Email"/"Password", but the visible
    // placeholder text is the distinct copy, not a duplicate bold label above the field.
    expect(screen.getByLabelText('Email').props.placeholder).toBe('you@example.com');
    expect(screen.getByLabelText('Password').props.placeholder).toBe('Password');
    expect(screen.queryByText('Email')).toBeNull();
    expect(screen.getByText('Forgot your password?')).toBeTruthy();
    expect(screen.getByText('I already have an account')).toBeTruthy();
  });

  test('the language-row wrapper stretches full width so the toggle sits top-right, not top-left', async () => {
    Platform.OS = 'ios';
    await render(<WelcomeScreen />);

    // `justifyContent: 'flex-end'` alone isn't enough: inside Screen's headerRow (a plain
    // `flexDirection: 'row'` with no sizing of its own), a child with no `flex` shrinks to its
    // content width, so flex-end has no room to act and the toggle renders flush left. `flex: 1`
    // makes the row claim the full width so flex-end can push its content to the right edge.
    const row = StyleSheet.flatten(screen.getByTestId('welcome-language-row').props.style) as {
      flex?: number;
      justifyContent?: string;
    };
    expect(row.flex).toBe(1);
    expect(row.justifyContent).toBe('flex-end');
  });

  test('hides Continue with Apple on Android', async () => {
    Platform.OS = 'android';
    await render(<WelcomeScreen />);

    expect(screen.queryByRole('button', { name: 'Continue with Apple' })).toBeNull();
    expect(screen.getByRole('button', { name: 'Continue with Google' })).toBeTruthy();
  });

  test('an empty email shows a translated message without calling the service', async () => {
    Platform.OS = 'ios';
    await render(<WelcomeScreen />);

    await fireEvent.changeText(screen.getByLabelText('Password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Create account' }));

    expect(await screen.findByText('Enter your email.')).toBeTruthy();
    expect(mockedSignUpWithEmail).not.toHaveBeenCalled();
  });

  test('a malformed email shows a translated message without calling the service', async () => {
    Platform.OS = 'ios';
    await render(<WelcomeScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'not-an-email');
    await fireEvent.changeText(screen.getByLabelText('Password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Create account' }));

    expect(await screen.findByText('Enter a valid email address.')).toBeTruthy();
    expect(mockedSignUpWithEmail).not.toHaveBeenCalled();
  });

  test('a short password shows the weak-password error without calling the service', async () => {
    Platform.OS = 'ios';
    await render(<WelcomeScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'short@example.com');
    await fireEvent.changeText(screen.getByLabelText('Password'), 'short1');
    await fireEvent.press(screen.getByRole('button', { name: 'Create account' }));

    expect(await screen.findByText('Use at least 8 characters.')).toBeTruthy();
    expect(mockedSignUpWithEmail).not.toHaveBeenCalled();
  });

  test('trims the email before calling the service', async () => {
    Platform.OS = 'ios';
    mockedSignUpWithEmail.mockResolvedValue({ ok: true, needsConfirmation: false });
    await render(<WelcomeScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), '  spaced@example.com  ');
    await fireEvent.changeText(screen.getByLabelText('Password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Create account' }));

    await waitFor(() => {
      expect(mockedSignUpWithEmail).toHaveBeenCalledWith('spaced@example.com', 'longenough1');
    });
  });

  test('a network error from the service shows its message and keeps the typed email', async () => {
    Platform.OS = 'ios';
    mockedSignUpWithEmail.mockResolvedValue({ ok: false, error: 'auth.error.network' });
    await render(<WelcomeScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'keep-me@example.com');
    await fireEvent.changeText(screen.getByLabelText('Password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Create account' }));

    expect(await screen.findByText("Couldn't connect. Check your internet and try again.")).toBeTruthy();
    expect(screen.getByLabelText('Email').props.value).toBe('keep-me@example.com');
  });

  test('ok + needsConfirmation true shows the check-your-email message', async () => {
    Platform.OS = 'ios';
    mockedSignUpWithEmail.mockResolvedValue({ ok: true, needsConfirmation: true });
    await render(<WelcomeScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'new@example.com');
    await fireEvent.changeText(screen.getByLabelText('Password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Create account' }));

    expect(await screen.findByText('Check your email to confirm your account before signing in.')).toBeTruthy();
  });

  test('ok + needsConfirmation false shows no message (confirmations off locally)', async () => {
    Platform.OS = 'ios';
    mockedSignUpWithEmail.mockResolvedValue({ ok: true, needsConfirmation: false });
    await render(<WelcomeScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'new@example.com');
    await fireEvent.changeText(screen.getByLabelText('Password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Create account' }));

    await waitFor(() => {
      expect(mockedSignUpWithEmail).toHaveBeenCalledTimes(1);
    });
    expect(screen.queryByText('Check your email to confirm your account before signing in.')).toBeNull();
  });

  test('tapping Continue with Apple calls signInWithApple', async () => {
    Platform.OS = 'ios';
    mockedSignInWithApple.mockResolvedValue({ ok: true });
    await render(<WelcomeScreen />);

    await fireEvent.press(screen.getByRole('button', { name: 'Continue with Apple' }));
    await waitFor(() => {
      expect(mockedSignInWithApple).toHaveBeenCalledTimes(1);
    });
  });

  test('tapping Continue with Google calls signInWithGoogle', async () => {
    Platform.OS = 'ios';
    mockedSignInWithGoogle.mockResolvedValue({ ok: true });
    await render(<WelcomeScreen />);

    await fireEvent.press(screen.getByRole('button', { name: 'Continue with Google' }));
    await waitFor(() => {
      expect(mockedSignInWithGoogle).toHaveBeenCalledTimes(1);
    });
  });

  test('a cancelled social sign-in shows no error message', async () => {
    Platform.OS = 'ios';
    mockedSignInWithGoogle.mockResolvedValue({ ok: false, error: 'auth.error.cancelled' });
    await render(<WelcomeScreen />);

    await fireEvent.press(screen.getByRole('button', { name: 'Continue with Google' }));
    await waitFor(() => {
      expect(mockedSignInWithGoogle).toHaveBeenCalledTimes(1);
    });
    expect(screen.queryByText('Sign-in was cancelled.')).toBeNull();
  });

  test('a social error renders inside the social section, not under the password field', async () => {
    Platform.OS = 'ios';
    mockedSignInWithGoogle.mockResolvedValue({ ok: false, error: 'auth.error.network' });
    await render(<WelcomeScreen />);

    await fireEvent.press(screen.getByRole('button', { name: 'Continue with Google' }));
    await screen.findByText("Couldn't connect. Check your internet and try again.");

    // A real placement check (the password field's own `value` says nothing about where the error
    // text actually renders): the message must be a
    // descendant of the social section's container, and must not also appear as the password
    // TextField's `error` text (TextField always renders its own error inside its own container,
    // so if it had been passed there it would show up as a second, separate instance).
    const socialSection = screen.getByTestId('welcome-social-section');
    expect(within(socialSection).getByText("Couldn't connect. Check your internet and try again.")).toBeTruthy();
    expect(
      screen.getAllByText("Couldn't connect. Check your internet and try again.").length,
    ).toBe(1);
  });

  test('social buttons are disabled while a social sign-in is in flight', async () => {
    Platform.OS = 'ios';
    let resolveApple: (value: { ok: true }) => void = () => {};
    mockedSignInWithApple.mockReturnValue(
      new Promise((resolve) => {
        resolveApple = resolve;
      }),
    );
    await render(<WelcomeScreen />);

    await fireEvent.press(screen.getByRole('button', { name: 'Continue with Apple' }));

    await waitFor(() => {
      expect(screen.getByRole('button', { name: 'Continue with Google' })).toBeDisabled();
    });
    // "Create account" must also be disabled during a social sign-in — a tap there mid-flow
    // would otherwise fire signUpWithEmail concurrently with the pending Apple sign-in.
    expect(screen.getByRole('button', { name: 'Create account' })).toBeDisabled();

    resolveApple({ ok: true });
  });
});

describe('SignInScreen', () => {
  test('a success calls signInWithEmail and nothing else', async () => {
    mockedSignInWithEmail.mockResolvedValue({ ok: true });
    await render(<SignInScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'user@example.com');
    await fireEvent.changeText(screen.getByLabelText('Password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Sign in' }));

    await waitFor(() => {
      expect(mockedSignInWithEmail).toHaveBeenCalledWith('user@example.com', 'longenough1');
    });
    expect(mockedSignInWithEmail).toHaveBeenCalledTimes(1);
    // Navigation is driven by the root guard reacting to AuthProvider, not by this screen.
    expect(router.push).not.toHaveBeenCalled();
    expect(router.replace).not.toHaveBeenCalled();
  });

  test('an empty email shows a translated message without calling the service', async () => {
    await render(<SignInScreen />);

    await fireEvent.press(screen.getByRole('button', { name: 'Sign in' }));

    expect(await screen.findByText('Enter your email.')).toBeTruthy();
    expect(mockedSignInWithEmail).not.toHaveBeenCalled();
  });

  test('has a back control to welcome (a "Create an account" link, plus a labeled back chevron)', async () => {
    await render(<SignInScreen />);

    // The chevron is accessibilityRole="button" (labeled "Back"); the footer link is
    // accessibilityRole="link", so each query can only match its own control.
    expect(screen.getByRole('button', { name: 'Back' })).toBeTruthy();
    expect(screen.getByRole('link', { name: 'Create an account' })).toBeTruthy();
  });
});

describe('ForgotPasswordScreen', () => {
  test('step 1: Send code calls requestPasswordReset and advances to step 2', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));

    await waitFor(() => {
      expect(mockedRequestPasswordReset).toHaveBeenCalledWith('reset@example.com');
    });
    expect(await screen.findByLabelText('Code')).toBeTruthy();
  });

  test('step 1 has a back-to-sign-in control', async () => {
    await render(<ForgotPasswordScreen />);

    expect(screen.getByText('Back to sign in')).toBeTruthy();
  });

  test('step 2 shows the code (6-digit, numeric, one-time-code autofill), new password and Confirm', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));

    const codeField = await screen.findByLabelText('Code');
    expect(codeField.props.keyboardType).toBe('number-pad');
    expect(codeField.props.maxLength).toBe(6);
    expect(codeField.props.autoComplete).toBe('one-time-code');
    expect(codeField.props.textContentType).toBe('oneTimeCode');
    expect(screen.getByLabelText('New password')).toBeTruthy();
    expect(screen.getByLabelText('Confirm password')).toBeTruthy();
    expect(screen.getByRole('button', { name: 'Confirm' })).toBeTruthy();
  });

  test('a code that is not 6 digits shows a format error under the Code field without calling confirmPasswordReset', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    await fireEvent.changeText(screen.getByLabelText('Code'), '123');
    await fireEvent.changeText(screen.getByLabelText('New password'), 'longenough1');
    await fireEvent.changeText(screen.getByLabelText('Confirm password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Confirm' }));

    expect(await screen.findByText('Enter the 6-digit code.')).toBeTruthy();
    expect(mockedConfirmPasswordReset).not.toHaveBeenCalled();
  });

  test('an invalidCode result shows the message, stays on step 2, and offers Send a new code', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    mockedConfirmPasswordReset.mockResolvedValue({ ok: false, error: 'auth.error.invalidCode' });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    await fireEvent.changeText(screen.getByLabelText('Code'), '123456');
    await fireEvent.changeText(screen.getByLabelText('New password'), 'longenough1');
    await fireEvent.changeText(screen.getByLabelText('Confirm password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Confirm' }));

    expect(await screen.findByText('That code is wrong or expired.')).toBeTruthy();
    expect(screen.getByLabelText('Code')).toBeTruthy();
    expect(screen.getByText('Send a new code')).toBeTruthy();
  });

  test('mismatched new/confirm passwords show an error under the password fields, not Code, without calling confirmPasswordReset', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    await fireEvent.changeText(screen.getByLabelText('Code'), '123456');
    await fireEvent.changeText(screen.getByLabelText('New password'), 'longenough1');
    await fireEvent.changeText(screen.getByLabelText('Confirm password'), 'different1');
    await fireEvent.press(screen.getByRole('button', { name: 'Confirm' }));

    expect(await screen.findByText("Passwords don't match.")).toBeTruthy();
    expect(mockedConfirmPasswordReset).not.toHaveBeenCalled();
    // A password error belongs under the password fields, not under the Code field with the code
    // errors. `TextField` gives its own outer container a `${testID}-container` testID, so
    // this confirms the message is NOT inside Code's container (it's under Confirm password's).
    const codeContainer = screen.getByTestId('forgot-password-code-container');
    expect(within(codeContainer).queryByText("Passwords don't match.")).toBeNull();
    const confirmPasswordContainer = screen.getByTestId('forgot-password-confirm-password-container');
    expect(within(confirmPasswordContainer).getByText("Passwords don't match.")).toBeTruthy();
  });

  test('a weak new password shows an error under the password fields, not Code', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    await fireEvent.changeText(screen.getByLabelText('Code'), '123456');
    await fireEvent.changeText(screen.getByLabelText('New password'), 'short1');
    await fireEvent.changeText(screen.getByLabelText('Confirm password'), 'short1');
    await fireEvent.press(screen.getByRole('button', { name: 'Confirm' }));

    expect(await screen.findByText('Use at least 8 characters.')).toBeTruthy();
    expect(mockedConfirmPasswordReset).not.toHaveBeenCalled();
  });

  test('a successful confirm does not navigate itself (the guard drives navigation)', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    mockedConfirmPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    await fireEvent.changeText(screen.getByLabelText('Code'), '123456');
    await fireEvent.changeText(screen.getByLabelText('New password'), 'longenough1');
    await fireEvent.changeText(screen.getByLabelText('Confirm password'), 'longenough1');
    await fireEvent.press(screen.getByRole('button', { name: 'Confirm' }));

    await waitFor(() => {
      expect(mockedConfirmPasswordReset).toHaveBeenCalledTimes(1);
    });
    expect(router.replace).not.toHaveBeenCalled();
    expect(router.push).not.toHaveBeenCalled();
  });

  test('step 2 offers a way back to step 1 to change the email', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    await fireEvent.press(screen.getByText('Change email'));

    expect(await screen.findByLabelText('Email')).toBeTruthy();
    expect(screen.queryByLabelText('Code')).toBeNull();
  });

  test('Send a new code shows a confirmation and is disabled while in flight', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    let resolveResend: (value: { ok: true }) => void = () => {};
    mockedRequestPasswordReset.mockReturnValue(
      new Promise((resolve) => {
        resolveResend = resolve;
      }),
    );
    await fireEvent.press(screen.getByText('Send a new code'));

    await waitFor(() => {
      expect(screen.getByRole('link', { name: 'Send a new code' })).toBeDisabled();
    });

    resolveResend({ ok: true });
    expect(await screen.findByText('A new code is on its way.')).toBeTruthy();
  });

  test('a resend failure shows a message on step 2, where the email field (and its error) is not shown', async () => {
    mockedRequestPasswordReset.mockResolvedValueOnce({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    mockedRequestPasswordReset.mockResolvedValueOnce({ ok: false, error: 'auth.error.network' });
    await fireEvent.press(screen.getByText('Send a new code'));

    expect(await screen.findByText("Couldn't connect. Check your internet and try again.")).toBeTruthy();
    // Still on step 2 — the email field (and its own, separate error slot) doesn't exist here.
    expect(screen.queryByLabelText('Email')).toBeNull();
  });

  test('Change email clears the typed code and any "code sent" confirmation', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');
    await fireEvent.changeText(screen.getByLabelText('Code'), '123456');
    await fireEvent.press(screen.getByText('Send a new code'));
    await screen.findByText('A new code is on its way.');

    await fireEvent.press(screen.getByText('Change email'));
    await screen.findByLabelText('Email');

    // Re-advancing to step 2 must not show the stale code value or the old "code sent" banner.
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    expect(await screen.findByLabelText('Code')).toHaveProp('value', '');
    expect(screen.queryByText('A new code is on its way.')).toBeNull();
  });

  test('the step-2 back chevron is labeled for its actual action (change email), not "back to sign in"', async () => {
    mockedRequestPasswordReset.mockResolvedValue({ ok: true });
    await render(<ForgotPasswordScreen />);

    await fireEvent.changeText(screen.getByLabelText('Email'), 'reset@example.com');
    await fireEvent.press(screen.getByRole('button', { name: 'Send code' }));
    await screen.findByLabelText('Code');

    expect(screen.getByRole('button', { name: 'Change email' })).toBeTruthy();
    expect(screen.queryByRole('button', { name: 'Back to sign in' })).toBeNull();
  });
});
